#!/usr/bin/env python3
"""
gen_pe_variants.py -- creates the two Task 4.2 variants of the Lab 5 PE from
rtl/eyeriss_v2_pe.v (the original stays the single source of truth):

    rtl/eyeriss_v2_pe_dsp.v    module eyeriss_v2_pe_dsp,   (* use_dsp = "yes" *)
    rtl/eyeriss_v2_pe_nodsp.v  module eyeriss_v2_pe_nodsp, (* use_dsp = "no" *)

The attribute has to sit on the module that contains the multipliers (Vivado
does not propagate use_dsp from a wrapper into its sub-modules), and Vivado
maps the PE's 8 x 8 multipliers to LUTs unless DSPs are requested explicitly.
"""
import os
import re

RTL = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rtl")


def main() -> None:
    src = open(os.path.join(RTL, "eyeriss_v2_pe.v")).read()
    if not re.search(r"\bmodule\s+eyeriss_v2_pe\s*\(", src):
        raise SystemExit("module eyeriss_v2_pe not found")
    for suffix, value in (("dsp", "yes"), ("nodsp", "no")):
        name = f"eyeriss_v2_pe_{suffix}"
        header = (
            f"// GENERATED by scripts/gen_pe_variants.py from eyeriss_v2_pe.v -- do not edit.\n"
            f"// Lab 5 PE with use_dsp = \"{value}\" (Task 4.2).\n"
        )
        body = re.sub(r"\bmodule\s+eyeriss_v2_pe\s*\(",
                      f"(* use_dsp = \"{value}\" *)\nmodule {name} (", src, count=1)
        path = os.path.join(RTL, f"{name}.v")
        text = header + body
        # parallel sweeps read these files; leave them alone when unchanged
        if os.path.exists(path) and open(path, newline="").read() == text:
            print(f"rtl/{name}.v up to date")
            continue
        with open(path, "w", newline="\n") as f:
            f.write(text)
        print(f"wrote rtl/{name}.v")


if __name__ == "__main__":
    main()
